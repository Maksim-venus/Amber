import { afterEach, describe, expect, it } from "vitest";
import { CONTEXT_SAFETY_RATIO } from "../../src/shared/defaults.ts";
import { promptText } from "../fixtures/llm/pipeline-llm.ts";
import { CurlClient } from "../fixtures/pipeline/curl.ts";
import { createDemoStack, type DemoStack } from "../fixtures/pipeline/demo-stack.ts";
import { LOCAL_TOKEN } from "../fixtures/pipeline/harness.ts";
import { evenCues } from "../fixtures/platform/subtitles.ts";

/**
 * End-to-end summary behaviour over the API on the replayed pipeline: template versions
 * and the rolling summary of a long lecture going stale when the primary changes.
 */

const TERMINAL = new Set(["succeeded", "failed", "cancelled"]);
const POLL_TIMEOUT_MS = 30_000;
const MAX_OUTPUT = 10;
/** Input room of the long-lecture model: well below the lecture, well above one chapter. */
const ROOM = 6000;

interface TaskDetail {
  statusProjection: string;
  stageRuns: Array<{ stage: string; status: string }>;
}

interface SummaryEntry {
  template: { id: string };
  artifactId?: string;
  current?: { id: string; transcriptRevisionId: string; partialIds?: string[]; promptRef?: { id: string; version: number } };
  stale: boolean;
  staleReason?: string;
}

const open: DemoStack[] = [];
afterEach(async () => {
  for (const stack of open.splice(0)) await stack.close();
});

async function setup(model: { contextWindowTokens: number; maxOutputTokens?: number }) {
  const stack = await createDemoStack();
  open.push(stack);
  const curl = new CurlClient(stack.baseUrl, LOCAL_TOKEN);
  const provider = await curl.request("POST", "/api/providers", {
    name: "replay",
    protocol: "openai_compatible",
    baseURL: "https://llm.example.com/v1",
    models: [{ modelId: "model-a", ...model }],
  });
  expect(provider.status).toBe(201);
  const providerProfileId = (provider.json as { id: string }).id;
  expect((await curl.request("PUT", `/api/providers/${providerProfileId}/credential`, { value: "<placeholder-llm-key>" })).status).toBe(200);
  return { stack, curl, modelRef: { providerProfileId, modelId: "model-a" } };
}

async function untilTerminal(curl: CurlClient, taskId: string): Promise<TaskDetail> {
  const deadline = Date.now() + POLL_TIMEOUT_MS;
  for (;;) {
    const task = (await curl.request("GET", `/api/tasks/${taskId}`)).json as TaskDetail;
    if (TERMINAL.has(task.statusProjection)) {
      return task;
    }
    if (Date.now() > deadline) {
      throw new Error(`task ${taskId} still ${task.statusProjection}`);
    }
    await new Promise((resolve) => setTimeout(resolve, 50));
  }
}

const statusesOf = (task: TaskDetail): Record<string, string> => Object.fromEntries(task.stageRuns.map((run) => [run.stage, run.status]));

async function importOne(curl: CurlClient, videoId: string, modelRef: object): Promise<{ contentId: string; task: TaskDetail }> {
  const imported = await curl.request("POST", "/api/contents/import", {
    items: [{ url: `https://www.youtube.com/watch?v=${videoId}` }],
    settings: { modelRef, autoProofread: false },
  });
  expect(imported.status).toBe(202);
  const { taskIds, contentIds } = imported.json as { taskIds: string[]; contentIds: string[] };
  return { contentId: contentIds[0] as string, task: await untilTerminal(curl, taskIds[0] as string) };
}

async function summaryOf(curl: CurlClient, contentId: string, templateId: string): Promise<SummaryEntry> {
  const response = await curl.request("GET", `/api/contents/${contentId}/summaries`);
  expect(response.status).toBe(200);
  const entry = (response.json as { templates: SummaryEntry[] }).templates.find((candidate) => candidate.template.id === templateId);
  if (entry === undefined) {
    throw new Error(`no summaries entry for ${templateId}`);
  }
  return entry;
}

describe("summaries over the replayed pipeline", () => {
  it("editing a template versions it; the new summary records v2 and the old one keeps v1", { timeout: 60_000 }, async () => {
    const { stack, curl, modelRef } = await setup({ contextWindowTokens: 128_000 });
    stack.h.platforms.youtube.video("j5template1", {
      metadata: { durationMs: 30_000, rawLanguage: "zh-CN", subtitleTracks: [{ locator: "zh", language: "zh-CN", autoGenerated: false, translated: false }] },
      subtitles: { zh: evenCues(3, 30_000, (index) => ["模板一句。", "模板二句。", "模板三句。"][index] as string) },
    });
    const { contentId, task } = await importOne(curl, "j5template1", modelRef);
    expect(task.statusProjection).toBe("succeeded");

    const created = await curl.request("POST", "/api/summary-templates", { name: "三句话", prompt: "用三句话总结这段内容。" });
    expect(created.status).toBe(201);
    const templateId = (created.json as { id: string }).id;
    const first = await curl.request("POST", `/api/contents/${contentId}/summaries`, { templateId, modelRef });
    expect(first.status).toBe(202);
    expect((await untilTerminal(curl, (first.json as { taskId: string }).taskId)).statusProjection).toBe("succeeded");

    const patched = await curl.request("PATCH", `/api/summary-templates/${templateId}`, { prompt: "用五句话总结这段内容。" });
    expect(patched.status).toBe(200);
    expect(patched.json).toMatchObject({ currentVersion: 2 });
    const second = await curl.request("POST", `/api/contents/${contentId}/summaries`, { templateId, modelRef });
    expect(second.status).toBe(202);
    expect((await untilTerminal(curl, (second.json as { taskId: string }).taskId)).statusProjection).toBe("succeeded");
    expect(promptText(stack.llm.calls.at(-1)?.request as never)).toContain("用五句话总结这段内容。");

    const entry = await summaryOf(curl, contentId, templateId);
    const revisions = await curl.request("GET", `/api/summaries/${entry.artifactId}/revisions`);
    expect(revisions.status).toBe(200);
    const list = revisions.json as { currentRevisionId: string; items: Array<{ id: string; promptRef?: { id: string; version: number } }> };
    expect(list.items.map((item) => item.promptRef)).toEqual([
      { id: templateId, version: 1 },
      { id: templateId, version: 2 },
    ]);
    expect(list.currentRevisionId).toBe(list.items[1]?.id);
    const versions = await curl.request("GET", `/api/summary-templates/${templateId}/versions`);
    expect((versions.json as { items: Array<{ version: number }> }).items.map((item) => item.version)).toEqual([1, 2]);
  });

  it("a long lecture rolls chapter by chapter; switching the primary makes the summary stale without any call", { timeout: 60_000 }, async () => {
    const { stack, curl, modelRef } = await setup({
      contextWindowTokens: Math.ceil((ROOM + MAX_OUTPUT) / CONTEXT_SAFETY_RATIO),
      maxOutputTokens: MAX_OUTPUT,
    });
    const long = Array.from({ length: 12 }, (_, i) => `第${String(i + 1).padStart(2, "0")}句${"内容".repeat(200)}`);
    stack.h.platforms.youtube.video("j9longlectu", {
      metadata: {
        durationMs: 12_000,
        rawLanguage: "zh-CN",
        subtitleTracks: [{ locator: "zh", language: "zh-CN", autoGenerated: false, translated: false }],
        chapters: [0, 4000, 8000].map((startMs, index) => ({ startMs, title: `第 ${index + 1} 章` })),
      },
      subtitles: { zh: evenCues(long.length, 12_000, (index) => long[index] as string) },
    });
    const { contentId, task } = await importOne(curl, "j9longlectu", modelRef);
    expect(statusesOf(task)).toEqual({
      source: "succeeded",
      subtitle: "succeeded",
      asr: "skipped",
      proofread: "skipped",
      chapter: "skipped",
      summary: "succeeded",
    });
    expect(stack.llm.kinds()).toEqual(["partial", "carry", "partial", "carry", "partial", "carry", "final"]);

    const fresh = await summaryOf(curl, contentId, "summary.core");
    expect(fresh.stale).toBe(false);
    expect(fresh.current?.partialIds).toHaveLength(3);
    const base = fresh.current?.transcriptRevisionId as string;

    const calls = stack.llm.calls.length;
    const subtitle = "1\n00:00:00,000 --> 00:00:12,000\n用户导入的字幕。\n";
    const importedSubtitle = await curl.request("POST", `/api/contents/${contentId}/subtitle-import`, { text: subtitle, format: "srt", language: "zh-CN" });
    expect(importedSubtitle.status).toBe(201);
    const primary = (importedSubtitle.json as { transcriptRevisionId: string }).transcriptRevisionId;
    expect((await curl.request("PUT", `/api/contents/${contentId}/primary-transcript`, { revisionId: primary })).status).toBe(200);

    const stale = await summaryOf(curl, contentId, "summary.core");
    expect(stale).toMatchObject({ stale: true, staleReason: "transcript_changed" });
    expect(stack.llm.calls.length).toBe(calls);

    // Back to the transcript it was built from: fresh again, still without a call.
    expect((await curl.request("PUT", `/api/contents/${contentId}/primary-transcript`, { revisionId: base })).status).toBe(200);
    expect((await summaryOf(curl, contentId, "summary.core")).stale).toBe(false);
    expect(stack.llm.calls.length).toBe(calls);
  });
});
