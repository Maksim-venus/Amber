import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import * as identity from "../../src/shared/app-identity.ts";
import * as backupNames from "../../src/shared/backup-names.ts";
import { CACHE_EXTENSIONS } from "../../src/shared/cache-file-name.ts";
import * as defaults from "../../src/shared/defaults.ts";
import { INSTALLER_COPY, INSTALLER_LOCALES, NSIS_LANGUAGES } from "../../src/shared/i18n/installer.ts";
import { renderDesktopDefaults, renderDesktopIdentity, renderShellCopy, rustString } from "../../src/tooling/export-desktop-defaults.ts";
import { INSTALLER_HOOKS_FILE } from "../../src/tooling/export-installer-hooks.ts";

const REPO_ROOT = join(import.meta.dirname, "..", "..");

const tauriConf = JSON.parse(readFileSync(join(REPO_ROOT, "src", "desktop", "tauri.conf.json"), "utf8")) as {
  identifier: string;
  app: {
    appDirectoriesOverride: Record<string, string>;
    security: { assetProtocol: { enable: boolean; scope: string[] } };
  };
  bundle: { windows: { nsis: { installMode: string; languages: string[]; installerHooks: string } } };
};

describe("renderDesktopDefaults", () => {
  it("renders the sidecar defaults as Rust constants with the values from defaults.ts", () => {
    const rust = renderDesktopDefaults();
    expect(rust).toContain(`pub const SIDECAR_READY_TIMEOUT_MS: u64 = ${defaults.SIDECAR_READY_TIMEOUT_MS};`);
    expect(rust).toContain(`pub const SIDECAR_RESTART_MAX: u32 = ${defaults.SIDECAR_RESTART_MAX};`);
    expect(rust).toContain(`pub const SIDECAR_SHUTDOWN_GRACE_MS: u64 = ${defaults.SIDECAR_SHUTDOWN_GRACE_MS};`);
    expect(rust.startsWith("// Generated by")).toBe(true);
  });
});

describe("renderDesktopIdentity", () => {
  it("renders the names from app-identity.ts unchanged", () => {
    const rust = renderDesktopIdentity();
    expect(rust).toContain(`pub const APP_IDENTIFIER: &str = "${identity.APP_IDENTIFIER}";`);
    expect(rust).toContain(`pub const DATA_DIR_NAME: &str = "${identity.DATA_DIR_NAME}";`);
    expect(rust).toContain(`pub const CACHE_DIR_NAME: &str = "${identity.CACHE_DIR_NAME}";`);
    expect(rust).toContain(`pub const DATA_ROOT_MARKER_MAGIC: &str = "${identity.DATA_ROOT_MARKER_MAGIC}";`);
    expect(rust).toContain(`pub const CACHE_ROOT_MARKER: &str = "${identity.CACHE_ROOT_MARKER}";`);
    expect(rust).toContain(`pub const CACHE_EXTENSIONS: &[&str] = &[${CACHE_EXTENSIONS.map((ext) => `"${ext}"`).join(", ")}];`);
    // The keyring entry the shell reads must keep its names, or every stored secret is orphaned.
    expect(rust).toContain('pub const MASTER_KEY_SERVICE: &str = "com.lifefindsitsway.amber";');
    // Where the shell finds the key of builds under the old identifier.
    expect(rust).toContain('pub const LEGACY_APP_IDENTIFIER: &str = "io.github.lifefindsitsway.amber";');
    expect(rust).toContain('pub const MASTER_KEY_ACCOUNT: &str = "master-key-v1";');
    // The backup names the shell shares with the restore command and the web client.
    expect(rust).toContain(`pub const BACKUP_FILE_EXTENSION: &str = "${backupNames.BACKUP_FILE_EXTENSION}";`);
    expect(rust).toContain(`pub const RESTORED_ORIGINALS_DIR_PREFIX: &str = "${backupNames.RESTORED_ORIGINALS_DIR_PREFIX}";`);
    expect(rust).toContain(`pub const RESTORE_PROGRESS_PREFIX: &str = "${backupNames.RESTORE_PROGRESS_PREFIX}";`);
  });
});

describe("renderShellCopy", () => {
  it("renders every shell message of both languages", () => {
    const rust = renderShellCopy();
    for (const locale of INSTALLER_LOCALES) {
      for (const text of Object.values(INSTALLER_COPY[locale].shell)) {
        expect(rust).toContain(rustString(text));
      }
    }
    expect(rust).toContain("pub const SHELL_COPY_ZH_CN: ShellCopy = ShellCopy {");
    expect(rust).toContain("pub const SHELL_COPY_EN: ShellCopy = ShellCopy {");
  });
});

describe("rustString", () => {
  it("escapes quotes, backslashes and control characters and keeps other text", () => {
    expect(rustString('a "b" \\ c')).toBe('"a \\"b\\" \\\\ c"');
    expect(rustString("一\n二\r\t")).toBe('"一\\n二\\r\\t"');
    expect(rustString("\u0000\u001f\u007f")).toBe('"\\u{0}\\u{1f}\\u{7f}"');
    expect(rustString("{path} 😀")).toBe('"{path} 😀"');
    expect(() => rustString("\ud800")).toThrow(/surrogate/u);
  });
});

describe("tauri.conf.json", () => {
  it("places the data and log directories, the identifier and the cache scope as app-identity.ts says", () => {
    expect(tauriConf.identifier).toBe(identity.APP_IDENTIFIER);
    expect(tauriConf.app.appDirectoriesOverride).toEqual({
      data: `$DATA/${identity.DATA_DIR_NAME}`,
      log: `$DATA/${identity.DATA_DIR_NAME}/${identity.LOG_DIR_NAME}`,
    });
    expect(tauriConf.app.security.assetProtocol).toEqual({ enable: true, scope: [`$APPDATA/${identity.CACHE_DIR_NAME}/**`] });
  });

  it("builds the installer per user, in both languages, with the generated uninstall hooks", () => {
    const nsis = tauriConf.bundle.windows.nsis;
    // The hooks use $APPDATA and the current user's credentials: per-user installs only.
    expect(nsis.installMode).toBe("currentUser");
    expect(nsis.languages).toEqual(["SimpChinese", "English"]);
    expect(INSTALLER_LOCALES).toEqual(["zh-CN", "en"]);
    // The installer template's LangStrings are declared per locale under these language names.
    expect(INSTALLER_LOCALES.map((locale) => NSIS_LANGUAGES[locale])).toEqual(nsis.languages);
    // The bundler resolves the path from src/desktop, like the resource paths.
    expect(join("src", "desktop", nsis.installerHooks)).toBe(join(INSTALLER_HOOKS_FILE));
  });
});
