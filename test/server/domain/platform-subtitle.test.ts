import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { monotonicFactory } from "ulid";
import {
  cueDigest,
  normalizePlatformChapters,
  originalSubtitleLanguage,
  platformTranscript,
  selectSubtitleTrack,
  usableCues,
  type TrackCandidate,
} from "../../../src/server/domain/platform-subtitle.ts";
import { checkTranscriptInvariants } from "../../../src/server/domain/transcript.ts";

const track = (language: string, autoGenerated = false, translated = false): TrackCandidate & { id: string } => ({
  id: `${language}${autoGenerated ? ":auto" : ""}${translated ? ":mt" : ""}`,
  language,
  autoGenerated,
  translated,
});

describe("originalSubtitleLanguage", () => {
  it("prefers the known raw language, otherwise the first track that is not a translation", () => {
    const tracks = [track("en", false, true), track("zh-CN", true), track("ja")];
    expect(originalSubtitleLanguage(tracks, "ja")).toBe("ja");
    expect(originalSubtitleLanguage(tracks, undefined)).toBe("zh-CN");
    expect(originalSubtitleLanguage([track("en", false, true)], undefined)).toBeUndefined();
  });
});

describe("selectSubtitleTrack", () => {
  it("ranks human original > automatic original > other human > other automatic > translation", () => {
    const ranked = [track("zh-Hans"), track("zh-CN", true), track("en"), track("fr", true), track("ja", false, true)];
    const remaining = [...ranked];
    const picked: string[] = [];
    while (remaining.length > 0) {
      // The track list order does not matter: reverse it to make sure.
      const best = selectSubtitleTrack([...remaining].reverse(), "zh");
      picked.push(best?.id as string);
      remaining.splice(remaining.indexOf(best as (typeof ranked)[number]), 1);
    }
    expect(picked).toEqual(["zh-Hans", "zh-CN:auto", "en", "fr:auto", "ja:mt"]);
  });

  it("compares languages by primary subtag and keeps the first of equal rank", () => {
    expect(selectSubtitleTrack([track("en-GB"), track("en-US")], "en")?.id).toBe("en-GB");
  });

  it("never prefers a translation into the original language over a real track", () => {
    expect(selectSubtitleTrack([track("zh", false, true), track("en", true)], "zh")?.id).toBe("en:auto");
  });

  it("returns undefined without tracks", () => {
    expect(selectSubtitleTrack([], "zh")).toBeUndefined();
  });
});

describe("usableCues", () => {
  it("rounds, trims, skips empty text, drops and counts broken timing, and sorts", () => {
    const { cues, dropped } = usableCues([
      { startMs: 2000.4, endMs: 3000.6, text: "  second " },
      { startMs: 0, endMs: 1000, text: "first" },
      { startMs: 1000, endMs: 1000, text: "zero length" },
      { startMs: -5, endMs: 10, text: "negative" },
      { startMs: Number.NaN, endMs: 10, text: "nan" },
      { startMs: 3000, endMs: 2000, text: "backwards" },
      { startMs: 4000, endMs: 5000, text: "   " },
    ]);
    expect(cues).toEqual([
      { startMs: 0, endMs: 1000, text: "first" },
      { startMs: 2000, endMs: 3001, text: "second" },
    ]);
    expect(dropped).toBe(4);
  });
});

describe("cueDigest", () => {
  const cues = [
    { startMs: 0, endMs: 1000, text: "a" },
    { startMs: 1000, endMs: 2000, text: "b" },
  ];

  it("is stable for equal content and changes with language, timing or text", () => {
    const digest = cueDigest("zh-CN", cues);
    expect(digest).toMatch(/^sha256:[0-9a-f]{64}$/);
    expect(cueDigest("zh-CN", cues.map((cue) => ({ ...cue })))).toBe(digest);
    expect(cueDigest("en", cues)).not.toBe(digest);
    expect(cueDigest("zh-CN", [cues[0] as (typeof cues)[number], { ...(cues[1] as (typeof cues)[number]), endMs: 2001 }])).not.toBe(digest);
    expect(cueDigest("zh-CN", [cues[0] as (typeof cues)[number], { ...(cues[1] as (typeof cues)[number]), text: "c" }])).not.toBe(digest);
  });
});

describe("platformTranscript", () => {
  it("builds a segment-only platform revision that satisfies the transcript invariants", () => {
    const { revision, segments } = platformTranscript({
      revisionId: "rev",
      contentId: "content",
      language: "zh-CN",
      cues: [
        { startMs: 0, endMs: 1000, text: "a" },
        { startMs: 1000, endMs: 2500, text: "b" },
      ],
      acquisition: "authenticated",
      newId: monotonicFactory(),
      createdAt: 7,
    });
    expect(revision).toEqual({
      id: "rev",
      contentId: "content",
      kind: "platform",
      language: "zh-CN",
      timingFidelity: "segment_only",
      generation: { kind: "platform", acquisition: "authenticated" },
      segmentCount: 2,
      createdAt: 7,
    });
    expect(segments.map(({ ordinal, startMs, endMs, text, revisionId, sourceSegmentIds }) => ({ ordinal, startMs, endMs, text, revisionId, sourceSegmentIds }))).toEqual([
      { ordinal: 0, startMs: 0, endMs: 1000, text: "a", revisionId: "rev", sourceSegmentIds: [] },
      { ordinal: 1, startMs: 1000, endMs: 2500, text: "b", revisionId: "rev", sourceSegmentIds: [] },
    ]);
    expect(new Set(segments.map((segment) => segment.id)).size).toBe(2);
    expect(checkTranscriptInvariants(revision, segments)).toEqual([]);
  });
});

describe("normalizePlatformChapters", () => {
  it("orders chapters, starts the first at 0 and derives missing ends from the next start and the duration", () => {
    expect(
      normalizePlatformChapters(
        [
          { startMs: 60_000, title: " Two " },
          { startMs: 5_000, title: "One" },
          { startMs: 120_000, title: "Three" },
        ],
        200_000,
      ),
    ).toEqual([
      { startMs: 0, endMs: 60_000, title: "One" },
      { startMs: 60_000, endMs: 120_000, title: "Two" },
      { startMs: 120_000, endMs: 200_000, title: "Three" },
    ]);
  });

  it("keeps given ends, clamps them to the duration and drops chapters without a positive span or beyond the end", () => {
    expect(
      normalizePlatformChapters(
        [
          { startMs: 0, endMs: 50_000.4, title: "A" },
          { startMs: 50_000, endMs: 250_000, title: "B" },
          { startMs: 90_000, endMs: 90_000, title: "empty" },
          { startMs: 200_000, title: "after the end" },
        ],
        100_000,
      ),
    ).toEqual([
      { startMs: 0, endMs: 50_000, title: "A" },
      { startMs: 50_000, endMs: 100_000, title: "B" },
    ]);
  });

  it("returns nothing for no chapters", () => {
    expect(normalizePlatformChapters([], 100_000)).toEqual([]);
  });
});

describe("recorded bilibili lecture", () => {
  const recorded = JSON.parse(readFileSync(new URL("../../fixtures/platform/recorded/bilibili-lecture-3.json", import.meta.url), "utf8")) as {
    metadata: { durationMs: number; chapters: Array<{ startMs: number; endMs?: number; title: string }>; subtitleTracks: TrackCandidate[] };
  };

  it("picks the original Chinese track over the five platform translations", () => {
    const tracks = recorded.metadata.subtitleTracks;
    expect(tracks.filter((track) => track.translated)).toHaveLength(5);
    expect(selectSubtitleTrack(tracks, undefined)).toMatchObject({ language: "zh", translated: false });
  });

  it("keeps chapter ends given in whole seconds within the media duration", () => {
    const chapters = normalizePlatformChapters(recorded.metadata.chapters, recorded.metadata.durationMs);
    expect(chapters).toHaveLength(3);
    expect(chapters.at(-1)?.endMs).toBe(recorded.metadata.durationMs);
    expect(chapters.map((chapter) => chapter.title)).toEqual(recorded.metadata.chapters.map((chapter) => chapter.title.trim()));
  });
});
