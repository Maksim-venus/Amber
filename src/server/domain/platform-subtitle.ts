import { createHash } from "node:crypto";
import type { SegmentId } from "../../shared/ids.ts";
import { canonicalJson } from "./canonical-json.ts";
import type { TranscriptRevision, TranscriptSegment } from "./transcript.ts";

/** What track selection needs to know about a platform subtitle track. */
export interface TrackCandidate {
  /** BCP-47 tag. */
  language: string;
  autoGenerated: boolean;
  translated: boolean;
}

function primarySubtag(tag: string): string {
  return tag.split("-")[0]?.toLowerCase() ?? "";
}

/**
 * The spoken language as far as the platform tells: the Content's `rawLanguage` when
 * known, otherwise the language of the first track that is not a platform translation
 * (the caller writes it back to `rawLanguage`).
 */
export function originalSubtitleLanguage<T extends TrackCandidate>(tracks: readonly T[], rawLanguage: string | undefined): string | undefined {
  return rawLanguage ?? tracks.find((track) => !track.translated)?.language;
}

/**
 * Track order: human track in the original language > automatic track in
 * the original language > other human tracks > platform translations. The output
 * language never pulls in a machine-translated track. `undefined` when there are none.
 */
export function selectSubtitleTrack<T extends TrackCandidate>(tracks: readonly T[], rawLanguage: string | undefined): T | undefined {
  const original = originalSubtitleLanguage(tracks, rawLanguage);
  const inOriginal = (track: T) => original !== undefined && primarySubtag(track.language) === primarySubtag(original);
  const rank = (track: T): number => {
    if (track.translated) {
      return 4;
    }
    if (inOriginal(track)) {
      return track.autoGenerated ? 1 : 0;
    }
    return track.autoGenerated ? 3 : 2;
  };
  return tracks.reduce<T | undefined>((best, track) => (best === undefined || rank(track) < rank(best) ? track : best), undefined);
}

export interface PlatformCue {
  startMs: number;
  endMs: number;
  text: string;
}

/**
 * Cues as they may become segments: whitespace-trimmed, empty ones skipped, and those
 * whose timing breaks `0 <= startMs < endMs` dropped and counted. Invariant: every
 * segment has valid timing.
 */
export function usableCues(cues: readonly PlatformCue[]): { cues: PlatformCue[]; dropped: number } {
  const kept: PlatformCue[] = [];
  let dropped = 0;
  for (const cue of cues) {
    const startMs = Math.round(cue.startMs);
    const endMs = Math.round(cue.endMs);
    if (!(Number.isFinite(startMs) && Number.isFinite(endMs) && startMs >= 0 && startMs < endMs)) {
      dropped += 1;
      continue;
    }
    const text = cue.text.trim();
    if (text !== "") {
      kept.push({ startMs, endMs, text });
    }
  }
  kept.sort((a, b) => a.startMs - b.startMs || a.endMs - b.endMs);
  return { cues: kept, dropped };
}

/** Content digest of a cue list; equal platform subtitles are stored once. */
export function cueDigest(language: string, cues: ReadonlyArray<Pick<PlatformCue, "startMs" | "endMs" | "text">>): string {
  const body = canonicalJson({ language, cues: cues.map((cue) => [cue.startMs, cue.endMs, cue.text]) });
  return `sha256:${createHash("sha256").update(body).digest("hex")}`;
}

/** The `platform` revision a fetched subtitle becomes. */
export function platformTranscript(input: {
  revisionId: string;
  contentId: string;
  language: string;
  cues: readonly PlatformCue[];
  acquisition: "guest" | "authenticated";
  newId: () => string;
  createdAt: number;
}): { revision: TranscriptRevision; segments: TranscriptSegment[] } {
  const segments = input.cues.map(
    (cue, ordinal): TranscriptSegment => ({
      id: input.newId() as SegmentId,
      revisionId: input.revisionId,
      ordinal,
      startMs: cue.startMs,
      endMs: cue.endMs,
      text: cue.text,
      sourceSegmentIds: [],
    }),
  );
  return {
    revision: {
      id: input.revisionId,
      contentId: input.contentId,
      kind: "platform",
      language: input.language,
      timingFidelity: "segment_only",
      generation: { kind: "platform", acquisition: input.acquisition },
      segmentCount: segments.length,
      createdAt: input.createdAt,
    },
    segments,
  };
}

export interface ChapterEntry {
  startMs: number;
  endMs: number;
  title: string;
}

/**
 * Platform chapters as stored in a `ChapterRevision(origin = platform)`: ordered, the first starting at 0, a missing end taken from the next chapter's
 * start and the last one's from the media duration; chapters left without a positive
 * span are dropped.
 */
export function normalizePlatformChapters(
  chapters: ReadonlyArray<{ startMs: number; endMs?: number; title: string }>,
  durationMs: number,
): ChapterEntry[] {
  const ordered = chapters
    .map((chapter) => ({ ...chapter, startMs: Math.max(0, Math.round(chapter.startMs)), title: chapter.title.trim() }))
    .filter((chapter) => Number.isFinite(chapter.startMs) && chapter.startMs < durationMs)
    .sort((a, b) => a.startMs - b.startMs);
  const first = ordered[0];
  if (first !== undefined) {
    first.startMs = 0;
  }
  const normalized: ChapterEntry[] = [];
  ordered.forEach((chapter, index) => {
    const next = ordered[index + 1];
    const fallbackEnd = next === undefined ? durationMs : next.startMs;
    const endMs = Math.min(chapter.endMs === undefined ? fallbackEnd : Math.round(chapter.endMs), durationMs);
    if (chapter.startMs < endMs) {
      normalized.push({ startMs: chapter.startMs, endMs, title: chapter.title });
    }
  });
  return normalized;
}
