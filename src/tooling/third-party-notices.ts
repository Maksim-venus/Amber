/**
 * The distribution notices the installer carries beside Amber's own `LICENSE`:
 * `THIRD_PARTY_NOTICES.md` lists every bundled component (the Runtime Assets files the
 * installer actually ships, npm production dependencies, Rust crates of the shell) and embeds
 * their license texts once each; `SOURCE.md` says where the source of Amber and the
 * corresponding source of the GPL FFmpeg build can be obtained. The download URLs are fixed at
 * build time from the verified Runtime Assets manifest (its release tag and the file names of
 * its compliance artifacts), so the files never change after signing.
 */

export const LICENSE_FILE = "LICENSE";
export const NOTICES_FILE = "THIRD_PARTY_NOTICES.md";
export const SOURCE_FILE = "SOURCE.md";

/**
 * Runtime Assets file holding the unmodified license and notice texts of each runtime
 * component, one entry per text named `<component>/<file>`.
 */
export const RUNTIME_LICENSES_ASSET = "runtime-licenses.zip";

/** Manifest artifact component: the complete corresponding source of FFmpeg and every component built into it. */
export const COMPLIANCE_SOURCE_COMPONENT = "ffmpeg-ccs";
/** Manifest artifact component: the license texts of the third-party components of the FFmpeg build. */
export const COMPLIANCE_LICENSES_COMPONENT = "third-party-licenses";
/** The platform of the FFmpeg build the installer ships, whose compliance artifacts `SOURCE.md` names. */
export const COMPLIANCE_PLATFORM = "win-x64";

/** Said in the notices when the crate list could only be read from `Cargo.lock`. */
export const CARGO_LOCK_ONLY_NOTE = "本表取自 `Cargo.lock`，列出锁定的全部 crate（含其他平台与构建期依赖）；许可证见各 crate 的发布信息。";

const WINDOWS_TARGET = "x86_64-pc-windows-msvc";

export interface RuntimeAsset {
  file: string;
  component: string;
  version: string;
  platform: string;
  sourceUrl?: string;
  license: string | null;
}

/** A file of the Runtime Assets release generated by the project rather than taken from upstream. */
export interface RuntimeArtifact {
  file: string;
  component: string;
  platform: string;
  version: string;
  sha256?: string;
  sizeBytes?: number;
  description?: string;
  license: string | null;
}

export interface RuntimeManifest {
  version: string;
  assets: RuntimeAsset[];
  /** Empty when the manifest predates the `artifacts` list. */
  artifacts: RuntimeArtifact[];
}

export interface LicenseText {
  file: string;
  text: string;
}

/** One bundled package with the license texts found beside it. */
export interface PackageNotice {
  name: string;
  version: string;
  license: string | null;
  texts: LicenseText[];
}

function requireStrings(entry: Record<string, unknown>, keys: readonly string[], kind: string): void {
  for (const key of keys) {
    if (typeof entry[key] !== "string") {
      throw new Error(`Runtime Assets manifest ${kind} entry lacks ${key}`);
    }
  }
}

export function parseRuntimeManifest(text: string): RuntimeManifest {
  const parsed = JSON.parse(text) as { version?: unknown; assets?: unknown; artifacts?: unknown };
  if (typeof parsed.version !== "string" || !Array.isArray(parsed.assets)) {
    throw new Error("Runtime Assets manifest.json lacks version or assets");
  }
  if (parsed.artifacts !== undefined && !Array.isArray(parsed.artifacts)) {
    throw new Error("Runtime Assets manifest.json artifacts is not a list");
  }
  const assets = parsed.assets.map((raw: unknown) => {
    const asset = raw as Record<string, unknown>;
    requireStrings(asset, ["file", "component", "version", "platform"], "asset");
    return {
      file: asset["file"] as string,
      component: asset["component"] as string,
      version: asset["version"] as string,
      platform: asset["platform"] as string,
      ...(typeof asset["sourceUrl"] === "string" ? { sourceUrl: asset["sourceUrl"] } : {}),
      license: typeof asset["license"] === "string" ? asset["license"] : null,
    };
  });
  const artifacts = ((parsed.artifacts ?? []) as unknown[]).map((raw: unknown): RuntimeArtifact => {
    const artifact = raw as Record<string, unknown>;
    requireStrings(artifact, ["file", "component", "platform", "version"], "artifact");
    return {
      file: artifact["file"] as string,
      component: artifact["component"] as string,
      platform: artifact["platform"] as string,
      version: artifact["version"] as string,
      ...(typeof artifact["sha256"] === "string" ? { sha256: artifact["sha256"] } : {}),
      ...(typeof artifact["sizeBytes"] === "number" ? { sizeBytes: artifact["sizeBytes"] } : {}),
      ...(typeof artifact["description"] === "string" ? { description: artifact["description"] } : {}),
      license: typeof artifact["license"] === "string" ? artifact["license"] : null,
    };
  });
  return { version: parsed.version, assets, artifacts };
}

/**
 * The file names of the compliance artifacts for the shipped FFmpeg build: its complete
 * corresponding source and its third-party license bundle. Both must be listed; without them
 * `SOURCE.md` could not name where the GPL source is offered.
 */
export function complianceArtifactsOf(manifest: RuntimeManifest): { sourceArchive: string; licensesArchive: string } {
  const find = (component: string): string => {
    const artifact = manifest.artifacts.find((entry) => entry.component === component && entry.platform === COMPLIANCE_PLATFORM);
    if (artifact === undefined) {
      throw new Error(`Runtime Assets manifest has no ${COMPLIANCE_PLATFORM} ${component} artifact`);
    }
    return artifact.file;
  };
  return { sourceArchive: find(COMPLIANCE_SOURCE_COMPONENT), licensesArchive: find(COMPLIANCE_LICENSES_COMPONENT) };
}

/** The version of the Windows FFmpeg build the installer ships. */
export function ffmpegVersionOf(manifest: RuntimeManifest): string {
  const ffmpeg = manifest.assets.find((asset) => asset.component === "ffmpeg" && asset.platform === "win-x64");
  if (ffmpeg === undefined) {
    throw new Error("Runtime Assets manifest has no win-x64 ffmpeg entry");
  }
  return ffmpeg.version;
}

const LICENSE_NAME = /^(?:licen[cs]e|copying|notice|unlicense)(?:[-._].*)?$/iu;

/** License, copying and notice files at the top of a package directory, in name order. */
export function licenseTextsIn(dir: string): LicenseText[] {
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir)
    .filter((name) => LICENSE_NAME.test(name) && statSync(join(dir, name)).isFile())
    .sort()
    .map((file) => ({ file, text: readFileSync(join(dir, file), "utf8") }));
}

/**
 * The license texts of each Runtime Assets component, read from the verified bytes of
 * `runtime-licenses.zip`: every entry `<component>/<file>` is one unmodified license or notice
 * text of that component. Any other entry shape is refused rather than guessed at.
 */
export function runtimeLicenseTexts(archive: Buffer): Map<string, LicenseText[]> {
  const texts = new Map<string, LicenseText[]>();
  for (const entry of readZip(archive)) {
    if (entry.name.endsWith("/")) {
      continue;
    }
    const match = /^([^/]+)\/([^/]+)$/u.exec(entry.name);
    if (match?.[1] === undefined || match[2] === undefined) {
      throw new Error(`${RUNTIME_LICENSES_ASSET} entry ${entry.name} is not <component>/<file>`);
    }
    const list = texts.get(match[1]) ?? [];
    list.push({ file: match[2], text: entry.read().toString("utf8") });
    texts.set(match[1], list);
  }
  for (const list of texts.values()) {
    // Code-unit order, as `Array.prototype.sort` gives, so the notices do not depend on the host locale.
    list.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  }
  return texts;
}

/**
 * Every package installed under `nodeModulesDir`, nested `node_modules` included: what the
 * sidecar actually ships, never the lockfile's wider view.
 */
export function collectNpmPackages(nodeModulesDir: string): PackageNotice[] {
  const seen = new Map<string, PackageNotice>();
  const visitPackage = (dir: string): void => {
    const manifestPath = join(dir, "package.json");
    if (!existsSync(manifestPath)) {
      return;
    }
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as { name?: unknown; version?: unknown; license?: unknown };
    if (typeof manifest.name === "string" && typeof manifest.version === "string") {
      const key = `${manifest.name}@${manifest.version}`;
      if (!seen.has(key)) {
        seen.set(key, { name: manifest.name, version: manifest.version, license: licenseOf(manifest.license), texts: licenseTextsIn(dir) });
      }
    }
    visitModules(join(dir, "node_modules"));
  };
  const visitModules = (modules: string): void => {
    if (!existsSync(modules)) {
      return;
    }
    for (const name of readdirSync(modules).sort()) {
      if (name.startsWith(".")) {
        continue;
      }
      const path = join(modules, name);
      if (!statSync(path).isDirectory()) {
        continue;
      }
      if (name.startsWith("@")) {
        for (const scoped of readdirSync(path).sort()) {
          visitPackage(join(path, scoped));
        }
      } else {
        visitPackage(path);
      }
    }
  };
  visitModules(nodeModulesDir);
  return [...seen.values()].sort(byNameVersion);
}

function licenseOf(value: unknown): string | null {
  if (typeof value === "string") {
    return value;
  }
  if (typeof value === "object" && value !== null && "type" in value && typeof value.type === "string") {
    return value.type;
  }
  return null;
}

function byNameVersion(a: { name: string; version: string }, b: { name: string; version: string }): number {
  return a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name);
}

/** The registry packages of a `Cargo.lock`: every platform, build and runtime dependencies alike. */
export function parseCargoLock(text: string): Array<{ name: string; version: string }> {
  const packages: Array<{ name: string; version: string }> = [];
  for (const block of text.split(/^\[\[package\]\]\s*$/mu).slice(1)) {
    const name = /^name\s*=\s*"([^"]+)"/mu.exec(block)?.[1];
    const version = /^version\s*=\s*"([^"]+)"/mu.exec(block)?.[1];
    // Local path packages (the shell itself) have no source.
    if (name !== undefined && version !== undefined && /^source\s*=/mu.test(block)) {
      packages.push({ name, version });
    }
  }
  return packages.sort(byNameVersion);
}

interface CargoMetadata {
  packages: Array<{ id: string; name: string; version: string; license: string | null; license_file: string | null; manifest_path: string; source: string | null }>;
  resolve: { root: string | null; nodes: Array<{ id: string; deps: Array<{ pkg: string; dep_kinds: Array<{ kind: string | null }> }> }> } | null;
}

/** The crates reachable from the shell through normal (not dev, not build) dependencies. */
export function cratesFromMetadata(metadata: CargoMetadata): PackageNotice[] {
  const resolve = metadata.resolve;
  if (resolve?.root === null || resolve === null) {
    throw new Error("cargo metadata has no resolved root");
  }
  const nodes = new Map(resolve.nodes.map((node) => [node.id, node]));
  const reached = new Set<string>();
  const queue = [resolve.root];
  while (queue.length > 0) {
    const id = queue.pop() as string;
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((kind) => kind.kind === null) && !reached.has(dep.pkg)) {
        reached.add(dep.pkg);
        queue.push(dep.pkg);
      }
    }
  }
  return metadata.packages
    .filter((pkg) => reached.has(pkg.id) && pkg.source !== null)
    .map((pkg) => {
      const dir = dirname(pkg.manifest_path);
      const texts = licenseTextsIn(dir);
      if (pkg.license_file !== null && !texts.some((text) => text.file === pkg.license_file)) {
        const path = join(dir, pkg.license_file);
        if (existsSync(path)) {
          texts.push({ file: pkg.license_file, text: readFileSync(path, "utf8") });
        }
      }
      return { name: pkg.name, version: pkg.version, license: pkg.license ?? (pkg.license_file === null ? null : `see ${pkg.license_file}`), texts };
    })
    .sort(byNameVersion);
}

/**
 * The shell's crates for Windows with their licenses, from `cargo metadata` where cargo is
 * available (the Windows build host). Elsewhere only `Cargo.lock` can be read: every locked
 * crate is listed, without license fields or texts, and `complete` is false.
 */
export function collectCargoPackages(desktopDir: string): { packages: PackageNotice[]; complete: boolean } {
  const result = spawnSync(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--filter-platform", WINDOWS_TARGET, "--manifest-path", join(desktopDir, "Cargo.toml")],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  if (result.status === 0) {
    return { packages: cratesFromMetadata(JSON.parse(result.stdout) as CargoMetadata), complete: true };
  }
  const lock = readFileSync(join(desktopDir, "Cargo.lock"), "utf8");
  return { packages: parseCargoLock(lock).map((pkg) => ({ ...pkg, license: null, texts: [] })), complete: false };
}

/** A Markdown fence longer than any backtick run inside `text`. */
function fenced(text: string): string {
  const longest = Math.max(2, ...Array.from(text.matchAll(/`+/gu), (match) => match[0].length));
  const fence = "`".repeat(longest + 1);
  return `${fence}text\n${text.replace(/\s+$/u, "")}\n${fence}`;
}

function cell(value: string): string {
  return value.replace(/\|/gu, "\\|").replace(/\r?\n/gu, " ");
}

export interface NoticesInput {
  amberVersion: string;
  runtime: RuntimeManifest;
  /** File names of the Runtime Assets the installer carries; only these are listed. */
  shippedAssets: Iterable<string>;
  runtimeTexts: ReadonlyMap<string, LicenseText[]>;
  npm: readonly PackageNotice[];
  cargo: readonly PackageNotice[];
  cargoComplete: boolean;
}

/**
 * The Runtime Assets entries of the shipped files, in manifest order. Fails when a shipped file
 * is not in the manifest or one of their components has no license text: the notices must
 * cover exactly what the installer carries, never more and never less.
 */
export function shippedRuntimeAssets(manifest: RuntimeManifest, shippedAssets: Iterable<string>, runtimeTexts: ReadonlyMap<string, LicenseText[]>): RuntimeAsset[] {
  const shipped = new Set(shippedAssets);
  const listed = new Set(manifest.assets.map((asset) => asset.file));
  const unlisted = [...shipped].filter((file) => !listed.has(file)).sort();
  if (unlisted.length > 0) {
    throw new Error(`shipped Runtime Assets missing from manifest.json: ${unlisted.join(", ")}`);
  }
  const assets = manifest.assets.filter((asset) => shipped.has(asset.file));
  const unlicensed = [...new Set(assets.map((asset) => asset.component))].filter((component) => (runtimeTexts.get(component) ?? []).length === 0).sort();
  if (unlicensed.length > 0) {
    throw new Error(`no license text in ${RUNTIME_LICENSES_ASSET} for shipped component(s): ${unlicensed.join(", ")}`);
  }
  return assets;
}

/**
 * Renders `THIRD_PARTY_NOTICES.md`: one table per source of components, then every distinct
 * license text once, headed by the components that carry it.
 */
export function renderThirdPartyNotices(input: NoticesInput): string {
  const runtimeAssets = shippedRuntimeAssets(input.runtime, input.shippedAssets, input.runtimeTexts);
  const texts = new Map<string, { text: string; users: string[] }>();
  const addTexts = (owner: string, list: readonly LicenseText[]): void => {
    for (const { file, text } of list) {
      const digest = createHash("sha256").update(text.replace(/\r\n/gu, "\n").trim()).digest("hex");
      const entry = texts.get(digest) ?? { text, users: [] };
      entry.users.push(`${owner}（${file}）`);
      texts.set(digest, entry);
    }
  };
  const lines: string[] = [
    "# 第三方组件声明",
    "",
    `Amber ${input.amberVersion} 的安装包除 Amber 自身（AGPL-3.0-only，见 \`${LICENSE_FILE}\`）外，还包含下列第三方组件。各组件按其各自的许可证分发；许可证全文附在本文末尾，每份相同的文本只列一次。`,
    "",
    `## 运行时组件（Amber Runtime Assets \`${input.runtime.version}\`）`,
    "",
    "| 组件 | 文件 | 版本 | 平台 | 许可证 | 来源 |",
    "|---|---|---|---|---|---|",
  ];
  for (const asset of runtimeAssets) {
    lines.push(
      `| ${cell(asset.component)} | ${cell(asset.file)} | ${cell(asset.version)} | ${cell(asset.platform)} | ${cell(asset.license ?? "—")} | ${cell(asset.sourceUrl ?? "—")} |`,
    );
  }
  for (const component of [...new Set(runtimeAssets.map((asset) => asset.component))].sort()) {
    addTexts(component, input.runtimeTexts.get(component) ?? []);
  }
  lines.push("", `FFmpeg 为 GPL 构建，其完整对应源码的获取方式见 \`${SOURCE_FILE}\`。`, "", "## npm 生产依赖（sidecar `server/node_modules`）", "");
  lines.push("| 包 | 版本 | 许可证 |", "|---|---|---|");
  for (const pkg of input.npm) {
    lines.push(`| ${cell(pkg.name)} | ${cell(pkg.version)} | ${cell(pkg.license ?? "—")} |`);
    addTexts(`${pkg.name}@${pkg.version}`, pkg.texts);
  }
  lines.push("", `## Rust 依赖（桌面外壳，目标 \`${WINDOWS_TARGET}\`）`, "");
  if (!input.cargoComplete) {
    lines.push(CARGO_LOCK_ONLY_NOTE, "");
  }
  lines.push("| crate | 版本 | 许可证 |", "|---|---|---|");
  for (const pkg of input.cargo) {
    lines.push(`| ${cell(pkg.name)} | ${cell(pkg.version)} | ${cell(pkg.license ?? "—")} |`);
    addTexts(`${pkg.name} ${pkg.version}`, pkg.texts);
  }
  lines.push("", "## 许可证全文", "");
  const ordered = [...texts.values()].sort((a, b) => (a.users[0] as string).localeCompare(b.users[0] as string));
  ordered.forEach((entry, index) => {
    lines.push(`### 文本 ${index + 1}`, "", `适用于：${entry.users.join("、")}`, "", fenced(entry.text), "");
  });
  return `${lines.join("\n").replace(/\n+$/u, "")}\n`;
}

export interface SourceNoticeInput {
  amberVersion: string;
  ffmpegVersion: string;
  /** The Runtime Assets release tag (`manifest.json` `version`) that carries the compliance artifacts. */
  runtimeAssetsVersion: string;
  /** File names of the compliance artifacts in that release. */
  sourceArchive: string;
  licensesArchive: string;
  /** The FFmpeg source commit and the build-script commit, from the Runtime Assets manifest. */
  ffmpegSourceCommit?: string;
  ffmpegBuildCommit?: string;
}

/** Renders `SOURCE.md`. */
export function renderSourceNotice(input: SourceNoticeInput): string {
  const lines = [
    "# 源码获取",
    "",
    `Amber 是自由软件，以 GNU Affero 通用公共许可证第 3 版（AGPL-3.0-only）发布。本安装包对应 Amber ${input.amberVersion}，源码位于：`,
    "",
    `- ${PUBLIC_REPOSITORY_URL}`,
    "",
    `安装包内的 FFmpeg 是以 GPL-3.0-or-later 发布的静态构建（版本 \`${input.ffmpegVersion}\`）。FFmpeg 及构建时链接进它的全部组件的完整对应源码、以及第三方许可证包，与安装包内的运行时组件发布在同一个 Amber Runtime Assets Release（资源仓库 ${RUNTIME_ASSETS_REPOSITORY_URL}，tag \`${input.runtimeAssetsVersion}\`）中，可从以下地址匿名下载：`,
    "",
    `- 完整对应源码：${runtimeAssetsDownloadUrl(input.runtimeAssetsVersion, input.sourceArchive)}`,
    `- 第三方许可证包：${runtimeAssetsDownloadUrl(input.runtimeAssetsVersion, input.licensesArchive)}`,
  ];
  if (input.ffmpegSourceCommit !== undefined) {
    lines.push("", `FFmpeg 源码提交：\`${input.ffmpegSourceCommit}\``);
  }
  if (input.ffmpegBuildCommit !== undefined) {
    lines.push("", `构建脚本（BtbN/FFmpeg-Builds）提交：\`${input.ffmpegBuildCommit}\``);
  }
  lines.push("", `其余第三方组件及其许可证见 \`${NOTICES_FILE}\`。`);
  return `${lines.join("\n")}\n`;
}

/** The FFmpeg source and build-script commits the Runtime Assets manifest records, when it does. */
export function ffmpegProvenanceOf(manifest: RuntimeManifest): { ffmpegSourceCommit?: string; ffmpegBuildCommit?: string } {
  const source = manifest.assets.find((asset) => asset.component === "ffmpeg-source")?.version;
  const build = manifest.assets.find((asset) => asset.component === "ffmpeg-build-info")?.version;
  return { ...(source === undefined ? {} : { ffmpegSourceCommit: source }), ...(build === undefined ? {} : { ffmpegBuildCommit: build }) };
}
