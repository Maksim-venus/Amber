import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  APP_IDENTIFIER,
  CACHE_DIR_NAME,
  CACHE_ROOT_MARKER,
  CACHE_ROOT_MARKER_MAGIC,
  DATA_DIR_NAME,
  DATA_ROOT_MARKER,
  DATA_ROOT_MARKER_MAGIC,
  LEGACY_APP_IDENTIFIER,
  MASTER_KEY_ACCOUNT,
  MASTER_KEY_SERVICE,
} from "../shared/app-identity.ts";
import { BACKUP_FILE_EXTENSION, RESTORE_PROGRESS_PREFIX, RESTORED_ORIGINALS_DIR_PREFIX } from "../shared/backup-names.ts";
import { CACHE_EXTENSIONS } from "../shared/cache-file-name.ts";
import { FILE_GRANT_TTL_MS, SIDECAR_READY_TIMEOUT_MS, SIDECAR_RESTART_MAX, SIDECAR_SHUTDOWN_GRACE_MS } from "../shared/defaults.ts";
import { INSTALLER_COPY, type InstallerLocale, type ShellCopy } from "../shared/i18n/installer.ts";

/**
 * Writes what the Rust shell needs from `src/shared` as Rust source, so the TypeScript
 * modules stay the only hand-maintained source:
 * - `defaults.rs`: the named defaults;
 * - `identity.rs`: directory, marker and credential names from `app-identity.ts`, the
 *   cache file extensions from `cache-file-name.ts`, and the backup names from `backup-names.ts`;
 * - `shell_copy.rs`: the shell's native message copy from `i18n/installer.ts`.
 * The output is generated and ignored by git; the shell pulls it in with `include!`.
 */

export const DESKTOP_DEFAULTS_FILE = "src/desktop/gen/defaults.rs";
export const DESKTOP_IDENTITY_FILE = "src/desktop/gen/identity.rs";
export const DESKTOP_SHELL_COPY_FILE = "src/desktop/gen/shell_copy.rs";

const HEADER = "// Generated by src/tooling/export-desktop-defaults.ts from src/shared. Do not edit.";

const EXPORTED: readonly (readonly [name: string, rustType: string, value: number])[] = [
  ["SIDECAR_READY_TIMEOUT_MS", "u64", SIDECAR_READY_TIMEOUT_MS],
  ["SIDECAR_RESTART_MAX", "u32", SIDECAR_RESTART_MAX],
  ["SIDECAR_SHUTDOWN_GRACE_MS", "u64", SIDECAR_SHUTDOWN_GRACE_MS],
  ["FILE_GRANT_TTL_MS", "u64", FILE_GRANT_TTL_MS],
];

const IDENTITY: readonly (readonly [name: string, value: string])[] = [
  ["APP_IDENTIFIER", APP_IDENTIFIER],
  ["LEGACY_APP_IDENTIFIER", LEGACY_APP_IDENTIFIER],
  ["DATA_DIR_NAME", DATA_DIR_NAME],
  ["CACHE_DIR_NAME", CACHE_DIR_NAME],
  ["DATA_ROOT_MARKER", DATA_ROOT_MARKER],
  ["DATA_ROOT_MARKER_MAGIC", DATA_ROOT_MARKER_MAGIC],
  ["CACHE_ROOT_MARKER", CACHE_ROOT_MARKER],
  ["CACHE_ROOT_MARKER_MAGIC", CACHE_ROOT_MARKER_MAGIC],
  ["MASTER_KEY_SERVICE", MASTER_KEY_SERVICE],
  ["MASTER_KEY_ACCOUNT", MASTER_KEY_ACCOUNT],
  ["BACKUP_FILE_EXTENSION", BACKUP_FILE_EXTENSION],
  ["RESTORED_ORIGINALS_DIR_PREFIX", RESTORED_ORIGINALS_DIR_PREFIX],
  ["RESTORE_PROGRESS_PREFIX", RESTORE_PROGRESS_PREFIX],
];

/** Rust constant names of the shell copy per locale. */
const SHELL_COPY_CONSTANTS: Readonly<Record<InstallerLocale, string>> = { "zh-CN": "SHELL_COPY_ZH_CN", en: "SHELL_COPY_EN" };

/** `ShellCopy` keys and the Rust field each becomes. */
const SHELL_COPY_FIELDS: readonly (readonly [key: keyof ShellCopy, field: string])[] = [
  ["title", "title"],
  ["dataDirForeign", "data_dir_foreign"],
  ["dataDirLink", "data_dir_link"],
  ["dataDirUnusable", "data_dir_unusable"],
];

/**
 * A Rust string literal for `value`: quotes, backslashes and control characters escaped,
 * everything else literal (the generated file is UTF-8).
 */
export function rustString(value: string): string {
  let out = '"';
  for (const char of value) {
    const code = char.codePointAt(0) as number;
    if (code >= 0xd800 && code <= 0xdfff) {
      throw new Error(`lone surrogate in ${JSON.stringify(value)}`);
    }
    if (char === '"' || char === "\\") {
      out += `\\${char}`;
    } else if (char === "\n") {
      out += "\\n";
    } else if (char === "\r") {
      out += "\\r";
    } else if (char === "\t") {
      out += "\\t";
    } else if (code < 0x20 || (code >= 0x7f && code <= 0x9f)) {
      out += `\\u{${code.toString(16)}}`;
    } else {
      out += char;
    }
  }
  return `${out}"`;
}

export function renderDesktopDefaults(): string {
  const lines = EXPORTED.map(([name, rustType, value]) => {
    if (!Number.isSafeInteger(value) || value < 0) {
      throw new Error(`${name} must be a non-negative integer, got ${value}`);
    }
    return `pub const ${name}: ${rustType} = ${value};`;
  });
  return [HEADER, ...lines, ""].join("\n");
}

export function renderDesktopIdentity(): string {
  const lines = IDENTITY.map(([name, value]) => `pub const ${name}: &str = ${rustString(value)};`);
  const extensions = `pub const CACHE_EXTENSIONS: &[&str] = &[${CACHE_EXTENSIONS.map(rustString).join(", ")}];`;
  return [HEADER, ...lines, extensions, ""].join("\n");
}

export function renderShellCopy(): string {
  const struct = [
    "/// The shell's native message copy in one language.",
    "pub struct ShellCopy {",
    ...SHELL_COPY_FIELDS.map(([, field]) => `    pub ${field}: &'static str,`),
    "}",
  ];
  const constants = Object.entries(SHELL_COPY_CONSTANTS).flatMap(([locale, constant]) => {
    const copy = INSTALLER_COPY[locale as InstallerLocale].shell;
    return [
      `pub const ${constant}: ShellCopy = ShellCopy {`,
      ...SHELL_COPY_FIELDS.map(([key, field]) => `    ${field}: ${rustString(copy[key])},`),
      "};",
    ];
  });
  return [HEADER, ...struct, ...constants, ""].join("\n");
}

function main(): void {
  const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
  for (const [file, render] of [
    [DESKTOP_DEFAULTS_FILE, renderDesktopDefaults],
    [DESKTOP_IDENTITY_FILE, renderDesktopIdentity],
    [DESKTOP_SHELL_COPY_FILE, renderShellCopy],
  ] as const) {
    const target = join(root, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, render());
    console.log(`wrote ${file}`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
